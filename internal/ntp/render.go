package ntp

import (
	"fmt"
	"path/filepath"
	"strings"
)

// Render returns the chrony configuration for cfg. stateDir holds the files
// written by chronyd itself (drift, NTS cookies). cfg must be valid.
func Render(cfg Config, stateDir string) string {
	var b strings.Builder
	b.WriteString("# Generated by EasyNetServices, do not edit: changes are overwritten.\n\n")

	for _, s := range cfg.Sources {
		b.WriteString(string(s.Type) + " " + s.Address)
		if s.IBurst {
			b.WriteString(" iburst")
		}
		if s.Prefer {
			b.WriteString(" prefer")
		}
		if s.NTS {
			b.WriteString(" nts")
		}
		b.WriteString("\n")
	}
	if len(cfg.Sources) > 0 {
		b.WriteString("\n")
	}

	for _, r := range cfg.Access {
		fmt.Fprintf(&b, "%s %s\n", r.Action, r.Network)
	}
	if len(cfg.Access) > 0 {
		b.WriteString("\n")
	}

	if cfg.LocalStratum > 0 {
		fmt.Fprintf(&b, "local stratum %d\n\n", cfg.LocalStratum)
	}

	fmt.Fprintf(&b, "driftfile %s\n", filepath.Join(stateDir, "chrony.drift"))
	fmt.Fprintf(&b, "ntsdumpdir %s\n", stateDir)
	// Step the clock on large offsets during the first updates; only effective
	// when chronyd is allowed to control the system clock.
	b.WriteString("makestep 1.0 3\n")
	// Management goes through the Unix socket only.
	b.WriteString("cmdport 0\n")
	return b.String()
}
