package dns

import (
	"fmt"
	"net/netip"
	"sort"
	"strings"
)

// Internal endpoints of the authoritative server. They listen on the loopback
// interface only and use uncommon ports, since the container shares the
// network of the host.
const (
	authDNSAddress = "127.0.0.1:15353"
	authAPIAddress = "127.0.0.1:18081"
)

// renderAuth returns the configuration of the PowerDNS Authoritative Server.
func renderAuth(dataDir, apiKey string) string {
	apiHost, apiPort, _ := strings.Cut(authAPIAddress, ":")
	return fmt.Sprintf(`# Generated by EasyNetServices, do not edit: changes are overwritten.
launch=gsqlite3
gsqlite3-database=%s/pdns.sqlite3
local-address=%s
api=yes
api-key=%s
webserver=yes
webserver-address=%s
webserver-port=%s
webserver-allow-from=127.0.0.1,::1
setuid=pdns
setgid=pdns
default-soa-content=ns.@ hostmaster.@ 0 10800 3600 604800 3600
loglevel=4
`, dataDir, authDNSAddress, apiKey, apiHost, apiPort)
}

// recursorInput gathers what the recursor configuration depends on.
type recursorInput struct {
	Settings Settings
	// LocalZones are the zones hosted by the authoritative server.
	LocalZones []string
	// IPv6 tells whether the host supports IPv6, to listen on "::" by default.
	IPv6      bool
	SocketDir string
}

// renderRecursor returns the YAML configuration of the PowerDNS Recursor.
// Every value comes from validated settings or zone names, so no quoting
// beyond the YAML flow syntax is needed.
func renderRecursor(in recursorInput) string {
	s := in.Settings
	var b strings.Builder
	b.WriteString("# Generated by EasyNetServices, do not edit: changes are overwritten.\n")

	b.WriteString("recursor:\n")
	b.WriteString("  setuid: pdns\n  setgid: pdns\n")
	fmt.Fprintf(&b, "  socket_dir: %s\n", in.SocketDir)

	// Local zones are answered by the authoritative server; user forward zones
	// with the same name are ignored.
	local := map[string]bool{}
	localZones := append([]string(nil), in.LocalZones...)
	sort.Strings(localZones)
	for _, z := range localZones {
		local[z] = true
	}

	var direct, recursive []string
	for _, z := range localZones {
		direct = append(direct, forwardEntry(z, []string{authDNSAddress}))
	}
	for _, z := range s.ForwardZones {
		if local[z.Name] {
			continue
		}
		servers := make([]string, 0, len(z.Servers))
		for _, srv := range z.Servers {
			ap, _ := parseServer(srv)
			servers = append(servers, ap.String())
		}
		if z.Recursive {
			recursive = append(recursive, forwardEntry(z.Name, servers))
		} else {
			direct = append(direct, forwardEntry(z.Name, servers))
		}
	}
	if s.Resolution == ResolutionForward {
		servers := make([]string, 0, len(s.Forwarders))
		for _, f := range s.Forwarders {
			port := uint16(53)
			if f.TLS {
				port = 853
			}
			servers = append(servers, netip.AddrPortFrom(netip.MustParseAddr(f.Address), port).String())
		}
		recursive = append(recursive, forwardEntry(".", servers))
	}
	if len(direct) > 0 {
		b.WriteString("  forward_zones:\n" + strings.Join(direct, ""))
	}
	if len(recursive) > 0 {
		b.WriteString("  forward_zones_recurse:\n" + strings.Join(recursive, ""))
	}

	listen := s.ListenAddresses
	if len(listen) == 0 {
		listen = []string{"0.0.0.0"}
		if in.IPv6 {
			listen = append(listen, "::")
		}
	}
	b.WriteString("incoming:\n")
	fmt.Fprintf(&b, "  listen: %s\n", flowList(listen))
	fmt.Fprintf(&b, "  allow_from: %s\n", flowList(s.AllowFrom))

	b.WriteString("outgoing:\n")
	// Forwarders on port 853 are queried with DNS over TLS.
	b.WriteString("  dot_to_port_853: true\n")

	b.WriteString("dnssec:\n")
	fmt.Fprintf(&b, "  validation: %s\n", s.DNSSEC)
	// Local and forwarded zones are usually not signed and may use names that
	// do not exist publicly: exclude them from DNSSEC validation.
	var ntas []string
	for _, z := range localZones {
		ntas = append(ntas, z)
	}
	for _, z := range s.ForwardZones {
		if !local[z.Name] {
			ntas = append(ntas, z.Name)
		}
	}
	if len(ntas) > 0 {
		b.WriteString("  negative_trustanchors:\n")
		for _, z := range ntas {
			fmt.Fprintf(&b, "  - name: %s\n    reason: Local or forwarded zone\n", z)
		}
	}

	b.WriteString("logging:\n  disable_syslog: true\n  timestamp: false\n")
	return b.String()
}

func forwardEntry(zone string, servers []string) string {
	return fmt.Sprintf("  - zone: %s\n    forwarders: %s\n", zone, flowList(servers))
}

func flowList(items []string) string {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = "'" + it + "'"
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}
